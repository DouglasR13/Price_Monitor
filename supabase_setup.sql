-- 1. Tabela de Usuários (Admin e Usuários Comuns)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
    telegram_chat_id TEXT DEFAULT '',
    failed_login_attempts INT DEFAULT 0,
    locked_until TIMESTAMPTZ,
    notification_hour INT DEFAULT 22,
    email_notifications_enabled BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Tabela de Produtos Monitorados
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    brand TEXT NOT NULL,
    category TEXT DEFAULT 'Geral',
    description TEXT DEFAULT '',
    search_query TEXT NOT NULL,
    target_price NUMERIC(10, 2),
    image_url TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Tabela de Histórico Temporal de Preços
CREATE TABLE IF NOT EXISTS public.price_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    checked_at TIMESTAMPTZ DEFAULT NOW(),
    min_price NUMERIC(10, 2) NOT NULL,
    max_price NUMERIC(10, 2) NOT NULL,
    avg_price NUMERIC(10, 2) NOT NULL,
    best_store TEXT NOT NULL,
    best_url TEXT,
    highest_store TEXT,
    recommendation TEXT NOT NULL, -- 'EXCELLENT', 'NORMAL', 'HIGH'
    recommendation_reason TEXT,
    delta_pct NUMERIC(6, 2) DEFAULT 0.0,
    delta_amount NUMERIC(10, 2) DEFAULT 0.0
);

-- 4. Tabela de Ofertas Individuais por Loja
CREATE TABLE IF NOT EXISTS public.store_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_record_id BIGINT NOT NULL REFERENCES public.price_records(id) ON DELETE CASCADE,
    store_name TEXT NOT NULL,
    product_title TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    url TEXT,
    is_best BOOLEAN DEFAULT FALSE
);

-- 5. Configurações de Sistema
CREATE TABLE IF NOT EXISTS public.system_settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Logs de Notificações (Telegram / E-mail)
CREATE TABLE IF NOT EXISTS public.notification_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    channel TEXT NOT NULL DEFAULT 'email',
    status TEXT NOT NULL,
    message TEXT NOT NULL,
    sent_at TIMESTAMPTZ DEFAULT NOW()
);

-- Índices de Performance
CREATE INDEX IF NOT EXISTS idx_products_user ON public.products(user_id);
CREATE INDEX IF NOT EXISTS idx_price_records_product ON public.price_records(product_id, checked_at DESC);
CREATE INDEX IF NOT EXISTS idx_users_email ON public.users(email);

